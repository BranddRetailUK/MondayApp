const test=require('node:test'),assert=require('node:assert/strict');
const {PGlite}=require('@electric-sql/pglite');
const express=require('express');
const {ensureCustomerGroupsTables}=require('../src/db/customerGroupsSchema');
const {createRouter}=require('../src/routes/customer-groups');
const {requireHubFullApiAccess}=require('../src/middleware/hubAuth');
test('groups persist, preserve customer identity, support multiple assignments, and safely delete only memberships',async t=>{
  const db=new PGlite();t.after(()=>db.close());
  await db.exec('CREATE TABLE database_jobs(customer_id INTEGER,customer_name TEXT,created_at_source TIMESTAMP,order_date TIMESTAMP); CREATE TABLE database_customer_profiles(customer_id INTEGER,customer_name TEXT,created_at_source TIMESTAMP,order_date TIMESTAMP)');
  await ensureCustomerGroupsTables(db);await ensureCustomerGroupsTables(db);
  await db.exec(`INSERT INTO database_jobs(customer_id,customer_name) VALUES(1,'School'),(1,'School'),(2,'Same name'),(3,'Same name'),(NULL,'Name only'); INSERT INTO database_customer_profiles(customer_id,customer_name) VALUES(NULL,'school'),(NULL,'New customer')`);
  const app=express();app.use(express.json());app.use((req,res,next)=>{if(req.get('x-access'))req.hubUser={access_scope:req.get('x-access')};next();});
  app.use('/api',requireHubFullApiAccess,createRouter(db));
  const server=app.listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));t.after(()=>new Promise(r=>server.close(r)));
  const request=async(path='',method='GET',body,access='full')=>{
    const response=await fetch(`http://127.0.0.1:${server.address().port}/api${path}`,{method,headers:{'Content-Type':'application/json',...(access?{'x-access':access}:{})},...(body?{body:JSON.stringify(body)}:{})});
    return {status:response.status,data:await response.json()};
  };
  assert.equal((await request('','GET',null,'')).status,401);assert.equal((await request('','GET',null,'dtf_only')).status,403);
  await db.exec("UPDATE database_jobs SET created_at_source='2025-01-01'; UPDATE database_customer_profiles SET created_at_source='2026-11-12';");
  const initial=(await request()).data;
  assert.equal(initial.customers.find(c=>c.key==='id:1').order_count,2);
  assert.match(initial.customers.find(c=>c.key==='id:1').added_at,/2025-01-01/);
  assert.match(initial.customers.find(c=>c.key==='name:new customer').added_at,/2026-11-12/);assert.equal(initial.groups.length,0);assert.equal(initial.customers.length,5);
  assert.equal(initial.customers.filter(c=>c.name.toLowerCase()==='school').length,1);
  assert.equal(initial.customers.filter(c=>c.name==='Same name').length,2);
  const group=(await request('/groups','POST',{title:'Schools',description:'Education'})).data;
  assert.equal((await request('/groups','POST',{title:' schools ',description:''})).status,409);
  assert.equal((await request('/groups','POST',{title:' ',description:''})).status,400);
  const second=(await request('/groups','POST',{title:'Corporate',description:''})).data;
  for(const id of [group.id,second.id,group.id])assert.equal((await request(`/groups/${id}/member`,'PUT',{key:'id:1',selected:true})).status,200);
  assert.equal((await request()).data.customers.find(c=>c.key==='id:1').groups.length,2);
  assert.equal((await request(`/groups/${group.id}/member`,'PUT',{key:'missing',selected:true})).status,404);
  await request(`/groups/${group.id}/member`,'PUT',{key:'name:new customer',selected:true});
  await db.exec("INSERT INTO database_jobs(customer_id,customer_name) VALUES(9,'New customer')");
  assert.deepEqual((await request()).data.customers.find(c=>c.key==='id:9').groups,[group.id]);
  await request(`/groups/${group.id}/member`,'PUT',{key:'id:9',selected:false});
  assert.deepEqual((await request()).data.customers.find(c=>c.key==='id:9').groups,[]);
  await request(`/groups/${group.id}`,'PUT',{title:'Education',description:'Schools and colleges'});
  assert.equal((await request()).data.groups.find(g=>g.id===group.id).title,'Education');
  await request(`/groups/${group.id}`,'DELETE');
  assert.deepEqual((await request()).data.customers.find(c=>c.key==='id:1').groups,[second.id]);
  assert.equal((await db.query('SELECT count(*)::int AS count FROM database_jobs')).rows[0].count,6);
  assert.equal((await request(`/groups/${group.id}/member`,'PUT',{key:'id:1',selected:true})).status,404);
});
