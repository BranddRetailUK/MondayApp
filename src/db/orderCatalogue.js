// Database style IDs above zero are existing Ralawise IDs. PenCarrie-only
// styles and colours use negative IDs allocated once, independent of CSV order.
const compactKey = column => `regexp_replace(lower(${column}), '[^a-z0-9]', '', 'g')`;
// Supplier brand labels differ for several ranges of the same manufacturer.
function brandKey(column) {
  const key = compactKey(column);
  return `CASE
    WHEN ${key} ~ '^(awdis)?(justhoods|justcool|justts|justpolos|ecologie|sodenim)$' THEN 'awdis'
    WHEN ${key} IN ('sf','sfclothing') THEN 'sf'
    WHEN ${key} IN ('flexfit','flexfitbyyupoong') THEN 'flexfit'
    WHEN ${key} LIKE 'result%' THEN 'result'
    WHEN ${key} IN ('spiro','spirorecycled') THEN 'spiro'
    WHEN ${key} IN ('karibanproact','proact') THEN 'proact'
    WHEN ${key} IN ('regattajunior','regattaprofessional') THEN 'regatta'
    ELSE ${key} END`;
}
const colourKey = column => `lower(btrim(translate(${column}, '†‡*△', '')))`;
function sizeKey(column) {
  const label = `upper(btrim(${column}))`;
  return `CASE ${label}
    WHEN 'XXS' THEN '2XS' WHEN 'XXL' THEN '2XL' WHEN 'XXXL' THEN '3XL' WHEN 'XXXXL' THEN '4XL'
    WHEN 'OS' THEN 'ONE SIZE' WHEN 'O/S' THEN 'ONE SIZE' WHEN 'ONESIZE' THEN 'ONE SIZE'
    ELSE regexp_replace(${label}, '^WOM ([0-9]+)$', '\\1') END`;
}

async function ensureOrderCatalogue(db) {
  await db.query(`
    ALTER TABLE proof_pencarrie_styles ADD COLUMN IF NOT EXISTS order_style_id integer GENERATED BY DEFAULT AS IDENTITY;
    ALTER TABLE proof_pencarrie_colours ADD COLUMN IF NOT EXISTS order_colour_id integer GENERATED BY DEFAULT AS IDENTITY;
    CREATE UNIQUE INDEX IF NOT EXISTS pc_order_style_id ON proof_pencarrie_styles(order_style_id);
    CREATE UNIQUE INDEX IF NOT EXISTS pc_order_colour_id ON proof_pencarrie_colours(order_colour_id);

    CREATE MATERIALIZED VIEW IF NOT EXISTS database_pc_style_map AS
      WITH manufacturers AS (
        SELECT ${brandKey('brand')} AS brand, ${compactKey("COALESCE(NULLIF(btrim(manufacturer_style_code),''),style_code)")} AS model, min(id) AS id
        FROM database_ralawise_catalog_styles
        GROUP BY 1,2 HAVING count(*)=1
      )
      SELECT p.code,p.name,COALESCE(m.id,-p.order_style_id) AS style_id
      FROM proof_pencarrie_styles p LEFT JOIN manufacturers m
        ON m.brand=${brandKey('p.brand')} AND m.model=${compactKey('p.supplier_code')}
       AND m.brand<>'' AND m.model<>'';
    CREATE UNIQUE INDEX IF NOT EXISTS pc_style_map_code ON database_pc_style_map(code);
    CREATE INDEX IF NOT EXISTS pc_style_map_style ON database_pc_style_map(style_id);

    CREATE MATERIALIZED VIEW IF NOT EXISTS database_pc_order_offers AS
      WITH live AS (
        SELECT v.style_id, ${colourKey('c.colour_name')} AS colour, ${sizeKey('v.size_name')} AS size
        FROM database_ralawise_catalog_variants v JOIN database_ralawise_catalog_colours c ON c.id=v.colour_id
        WHERE v.is_active GROUP BY 1,2,3
      )
      SELECT p.sku,p.style_code,p.colour_code,p.size,p.list_price,p.special_order,
             m.style_id,-c.order_colour_id AS colour_id,c.name AS colour,
             c.images->0->>'url' AS image_url,p.is_active AND live.style_id IS NULL AS available
      FROM proof_pencarrie_variants p JOIN database_pc_style_map m ON m.code=p.style_code
      JOIN proof_pencarrie_colours c ON c.style_code=p.style_code AND c.code=p.colour_code
      LEFT JOIN live ON live.style_id=m.style_id AND live.colour=${colourKey('c.name')} AND live.size=${sizeKey('p.size')};
    CREATE UNIQUE INDEX IF NOT EXISTS pc_order_offer_sku ON database_pc_order_offers(sku);
    CREATE INDEX IF NOT EXISTS pc_order_offer_style ON database_pc_order_offers(style_id) WHERE available;

    CREATE OR REPLACE VIEW database_order_styles AS
      SELECT id,style_code,manufacturer_style_code,style_name,brand,product_type,database_product_style_id
      FROM database_ralawise_catalog_styles
      UNION ALL
      SELECT m.style_id,p.code,p.supplier_code,p.name,p.brand,p.garment_type,NULL::integer
      FROM proof_pencarrie_styles p JOIN database_pc_style_map m ON m.code=p.code
      WHERE m.style_id<0 AND EXISTS (SELECT FROM database_pc_order_offers o WHERE o.style_id=m.style_id AND o.available);

    CREATE OR REPLACE VIEW database_order_colours AS
      SELECT id,colour_name,colour_code FROM database_ralawise_catalog_colours
      UNION ALL SELECT -order_colour_id,name,code FROM proof_pencarrie_colours;

    CREATE OR REPLACE VIEW database_order_variants AS
      SELECT id,style_id,colour_id,database_product_source_id,sku_code,alpha_sku_code,sku_status,
             primary_image_url,colour_image_url,carton_price,pack_price,single_price,size_code,size_name,
             is_active,'Ralawise'::text AS supplier_name,NULL::text AS pencarrie_sku
      FROM database_ralawise_catalog_variants
      UNION ALL
      SELECT NULL,style_id,colour_id,NULL,sku,NULL,CASE WHEN special_order THEN 'Special order' ELSE 'Active' END,
             image_url,image_url,list_price,NULL,list_price,size,size,true,'PenCarrie',sku
      FROM database_pc_order_offers WHERE available;
  `);
}

// Refresh inside the importing transaction so readers see one complete version.
async function refreshOrderCatalogue(db) {
  const {rows} = await db.query("SELECT to_regclass('database_pc_order_offers') AS relation");
  if (!rows[0]?.relation) return;
  await db.query('SELECT pg_advisory_xact_lock(75041103)');
  await db.query('REFRESH MATERIALIZED VIEW database_pc_style_map');
  await db.query('REFRESH MATERIALIZED VIEW database_pc_order_offers');
}
module.exports = {ensureOrderCatalogue,refreshOrderCatalogue,colourKey,sizeKey};
